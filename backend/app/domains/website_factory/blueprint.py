"""Website Blueprint Generator.

A blueprint is the complete, renderer-agnostic description of a site: pages,
sections (component + variant + content key), theme, navigation and business
facts. Content lives separately (website_content) so it can be cached,
regenerated by AI, or edited by the customer without touching structure.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Any

BLUEPRINT_SCHEMA_VERSION = 1

_PAGE_TITLES = {
    "home": "Home",
    "about": "About",
    "services": "Services",
    "faq": "FAQ",
    "contact": "Contact",
    "projects": "Projects",
    "gallery": "Gallery",
    "pricing": "Pricing",
    "team": "Team",
}


@dataclass(frozen=True)
class BlueprintBusiness:
    name: str
    industry: str
    industry_label: str
    city: str | None
    province: str | None
    address: str | None
    phone: str | None
    email: str | None
    facebook: str | None


@dataclass(frozen=True)
class BlueprintTemplate:
    slug: str
    version: int
    category: str
    pages: list[dict[str, Any]]
    theme: dict[str, Any]


def page_output_path(slug: str) -> str:
    return "index.html" if slug == "home" else f"{slug}/index.html"


def page_url_path(slug: str) -> str:
    return "" if slug == "home" else f"{slug}/"


def build_blueprint(
    *,
    subdomain: str,
    business: BlueprintBusiness,
    template: BlueprintTemplate,
    services: list[str],
    brand_tone: str | None,
    claimed: bool,
    features: dict[str, Any] | None = None,
) -> dict[str, Any]:
    """`features` (Phase 3): {"booking": bool, "chat": {"greeting": str} | None} - interactive modules
    the owner enabled and the plan includes. Booking adds a section to the contact page; chat is site-wide."""
    features = features or {"booking": False, "chat": None}
    pages = []
    for page in template.pages:
        slug = page["slug"]
        sections = [
            {
                "component": section["component"],
                "variant": section.get("variant", "standard"),
                "content_key": section.get("content_key", section["component"]),
            }
            for section in page.get("sections", [])
        ]
        if features.get("booking") and slug == "contact":
            sections.insert(0, {"component": "booking", "variant": "standard", "content_key": "booking"})
        pages.append(
            {
                "slug": slug,
                "title": page.get("title") or _PAGE_TITLES.get(slug, slug.title()),
                "path": page_url_path(slug),
                "output": page_output_path(slug),
                "sections": sections,
            }
        )
    return {
        "schema_version": BLUEPRINT_SCHEMA_VERSION,
        "subdomain": subdomain,
        "template": {"slug": template.slug, "version": template.version, "category": template.category},
        "theme": template.theme,
        "business": {
            "name": business.name,
            "industry": business.industry,
            "industry_label": business.industry_label,
            "city": business.city,
            "province": business.province,
            "address": business.address,
            "phone": business.phone,
            "email": business.email,
            "facebook": business.facebook,
        },
        "profile": {"services": services, "brand_tone": brand_tone},
        "navigation": [{"label": p["title"], "path": p["path"]} for p in pages],
        "pages": pages,
        "claim_banner": not claimed,
        "features": features,
    }


def content_keys(blueprint: dict[str, Any]) -> set[str]:
    return {s["content_key"] for p in blueprint.get("pages", []) for s in p.get("sections", [])}
